def tool_icon(icon, height=14):
    """Return an inline ``<img>`` tag for a toolbar icon.

    Parameters
    ----------
    icon : str
        One of the ``ICON_*`` data URIs in this module.
    height : int
        Rendered height in pixels.

    Returns
    -------
    str
        HTML suitable for embedding in sidebar help text.
    """
    return f"<img src='{icon}' height='{height}' style='vertical-align:middle;'/>"
